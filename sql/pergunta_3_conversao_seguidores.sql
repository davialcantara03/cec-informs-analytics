### Pergunta 3: Conversão de Seguidores — Quais dias da semana convertem melhor visitas ao perfil em novos seguidores?

Para responder a essa pergunta, os dados foram agrupados por dia da semana (`TO_CHAR` com `FMDay`) e ordenados pela sequência 
cronológica (`EXTRACT(DOW)`). A taxa de conversão foi calculada dividindo a soma de novos seguidores pela soma de visitas ao perfil 
em cada dia da semana.

**Resultado:**

| Dia da semana | Taxa de conversão em seguidores |
|---|---|
| Sunday | 1,93% |
| Monday | 2,16% |
| Tuesday | 3,67% |
| Wednesday | **3,80%** |
| Thursday | 2,06% |
| Friday | 2,22% |
| Saturday | 2,57% |

**Insight:** o meio da semana apresenta o maior pico de eficiência na retenção de público, com a **Quarta-feira (3,80%)** 
e a **Terça-feira (3,67%)** liderando disparadas. A Quarta-feira registra praticamente o dobro da taxa de conversão do 
**Domingo (1,93%)**, que é o pior dia da base. Isso indica que, embora os finais de semana possam acumular volume de impressões, os 
usuários que visitam o perfil na Terça e na Quarta possuem uma intenção de acompanhamento muito mais alta. Esses dois dias representam a 
janela ideal para publicar conteúdos estratégicos e aplicar chamadas para ação (*CTAs*) focadas em aquisição de novos seguidores.